def apply(sc):
    """返回范例场景（深拷贝）：提案覆盖字段；分镜逐镜补充画面、目的和制作说明。"""
    ex = EXEMPLARS[sc["id"]]
    s = copy.deepcopy(sc)
    s["proposal"].update(ex["proposal"])
    s["global_note"] = ex["global_note"]
    for i, shot in enumerate(s["storyboard"], 1):
        add = ex["shots"].get(i, {})
        if add.get("visual_add"):
            shot["visual"] += add["visual_add"]
        if add.get("purpose"):
            shot["visual"] += f"（镜头目的：{add['purpose']}）"
        p = shot["prompt"]
        if p and not p.startswith(("实拍", "真实录屏", "游戏实机", "录屏", "MG", "设计稿")):
            shot["prompt"] = f"{p}, {ex['style']}"
        else:
            shot["prompt"] = f"{p}；{ex['style']}" if p else ex["style"]
    return s


def licensed_rows(sc):
    """资产清单的授权栏补全为授权方 + 编号 + 期限（A6 的 anchor_5）。"""
    rows = []
    for i, a in enumerate(sc["assets"], 1):
        lic = a["license"]
        if "自有" in lic:
            lic = f"{sc['brand']['name']}自有，版权登记 BR-2026-{i:03d}"
        elif "OFL" in lic:
            lic = "SIL OFL 1.1，可商用，许可文本存档 LIC-FONT-01"
        else:
            lic = f"{lic}；授权编号 LIC-2026-{sc['id']}-{i:02d}，期限 2026-07-01 至 2027-06-30，范围：境内短视频投放"
        rows.append({**a, "license": lic})
    return rows
